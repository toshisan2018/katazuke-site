def toc(sections):
    lis = "".join(f'<li><a href="#{sid}">{t}</a></li>' for sid, t, _ in sections)
    return ('<nav class="k-toc" aria-label="目次"><p class="k-toc-h">目次</p>'
            f'<ol>{lis}</ol></nav>')


def body_from_sections(sections):
    out = []
    for sid, t, html in sections:
        out.append(f'<h2 id="{sid}">{t}</h2>')
        out.append(html)
    return "".join(out)


def article_jsonld(slug, title, desc):
    return {
        "@context": "https://schema.org",
        "@type": "Article",
        "headline": title,
        "description": desc,
        "inLanguage": "ja",
        "datePublished": TODAY_ISO,
        "dateModified": TODAY_ISO,
        "image": bp.IMG["ogp"],
        "author": {"@type": "Organization",
                   "name": bp.COMPANY_NAME + "（" + bp.SITE_NAME + "）",
                   "url": bp.DOMAIN + "/"},
        "publisher": {"@type": "Organization", "name": bp.COMPANY_NAME,
                      "logo": {"@type": "ImageObject", "url": bp.IMG["logo"]}},
        "mainEntityOfPage": {"@type": "WebPage", "@id": bp.DOMAIN + "/" + slug + "/"},
    }


def article_breadcrumb_jsonld(slug, title):
    return {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "ホーム", "item": bp.DOMAIN + "/"},
            {"@type": "ListItem", "position": 2, "name": "コラム", "item": bp.DOMAIN + "/column/"},
            {"@type": "ListItem", "position": 3, "name": title, "item": bp.DOMAIN + "/" + slug + "/"},
        ],
    }


