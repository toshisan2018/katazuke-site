NEWLINE = chr(10)


def update_llms_txt():
    path = os.path.join(bp.ROOT, "llms.txt")
    try:
        with io.open(path, encoding="utf-8") as f:
            txt = f.read()
    except IOError:
        print("  !! llms.txt が見つからないため更新をスキップ（先に build_pages.py を実行）")
        return
    lines = ["## コラム（解説記事）", "",
             "- [コラム一覧](" + bp.DOMAIN + "/column/): カテゴリ別の記事一覧。"]
    for cat in CAT_ORDER:
        in_cat = [a for a in ARTICLES if ART_CAT.get(a["slug"]) == cat]
        if not in_cat:
            continue
        lines += ["", "### " + cat, ""]
        for a in in_cat:
            lines.append("- [" + a["title"] + "](" + bp.DOMAIN + "/" + a["slug"] + "/): "
                         + a["desc"])
    new_sec = NEWLINE.join(lines)
    start = txt.find("## コラム（解説記事）")
    end = txt.find("## 問い合わせ")
    if start < 0 or end < 0 or end < start:
        print("  !! llms.txt のコラム節が見つからないため更新をスキップ")
        return
    txt = txt[:start] + new_sec + NEWLINE * 2 + txt[end:]
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(txt)
    print("llms.txt updated:", len(txt), "bytes")


update_llms_txt()
