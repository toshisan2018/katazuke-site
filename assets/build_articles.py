def add_article(slug, title, desc, lead, sections, faq, rel, answer=None):
    ans = (f'<div class="answer"><span class="answer-h">結論</span><p>{answer}</p></div>'
           if answer else '')
    art = ('<article class="prose k-article">'
           + f'<p class="lead">{lead}</p>'
           + ans
           + toc(sections)
           + body_from_sections(sections)
           + '</article>')
    parts = ['<div class="amt-katazuke">']
    parts.append(bp.header(""))
    parts.append('<div class="breadcrumb"><a href="/">ホーム</a>'
                 '<span>›</span><a href="/column/">コラム</a><span>›</span>' + title + '</div>')
    cat = ART_CAT.get(slug, "コラム")
    pub = PUB_DATE.get(slug, TODAY_ISO)
    pub_jp = pub.replace("-0", "-").split("-")
    pub_jp = f"{pub_jp[0]}年{int(pub_jp[1])}月{int(pub_jp[2])}日"
    upd = ('' if pub == UPDATED_ISO else
           f'<span class="art-upd">最終更新 <time datetime="{UPDATED_ISO}">{UPDATED_JP}</time></span>')
    parts.append('<div class="page-hero hero"><div class="hero-inner">'
                 f'<div class="art-meta"><span class="art-cat">{cat}</span>'
                 f'<time datetime="{pub}">{pub_jp} 公開</time>{upd}</div>'
                 f'<h1>{title}</h1></div></div>')
    ik = ART_ILLUST.get(slug)
    if ik:
        parts.append(f'<div class="svc-hero svc-hero--illust"><img src="{bp.IMG[ik]}" '
                     f'alt="{title}のイメージイラスト" width="560" height="520" loading="lazy"></div>')
    parts.append('<section class="k-section">' + art + '</section>')
    if slug in ("akiya-katazuke", "tenpo-heiten"):
        parts.append(bp.kaitai_banner())   # 解体サイトへの相互リンクバナー
    parts.append(bp.faq_block(faq))
    parts.append(author_box())
    parts.append('<!--RELCOL-->')
    parts.append(bp.rel_block(rel))
    parts.append(bp.cta())
    parts.append(bp.footer())
    parts.append('</div>')
    inner = "".join(parts)
    content = ('<!-- wp:html -->\n<style id="amt-katazuke-css">' + CSS + '</style>\n'
               + inner + '\n<!-- /wp:html -->')
    for j in [article_jsonld(slug, title, desc),
              article_breadcrumb_jsonld(slug, title),
              bp.faq_jsonld(faq)]:
        if j:
            content += ('\n\n<!-- wp:html -->\n<script type="application/ld+json">'
                        + json.dumps(j, ensure_ascii=False) + '</script>\n<!-- /wp:html -->')
    ARTICLES.append({"slug": slug, "title": title, "desc": desc, "content": content, "illust": ik})


