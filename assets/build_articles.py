def toc(sections):
    lis = "".join(f'<li><a href="#{sid}">{t}</a></li>' for sid, t, _ in sections)
    return ('<nav class="k-toc" aria-label="目次"><p class="k-toc-h">目次</p>'
            f'<ol>{lis}</ol></nav>')


def body_from_sections(sections):
    out = []
    for sid, t, html in sections:
        out.append(f'<h2 id="{sid}">{t}</h2>')
        out.append(html)
    return "".join(out)


def article_jsonld(slug, title, desc):
    return {
        "@context": "https://schema.org",
        "@type": "Article",
        "headline": title,
        "description": desc,
        "inLanguage": "ja",
        "datePublished": TODAY_ISO,
        "dateModified": TODAY_ISO,
        "image": bp.IMG["ogp"],
        "author": {"@type": "Organization",
                   "name": bp.COMPANY_NAME + "（" + bp.SITE_NAME + "）",
                   "url": bp.DOMAIN + "/"},
        "publisher": {"@type": "Organization", "name": bp.COMPANY_NAME,
                      "logo": {"@type": "ImageObject", "url": bp.IMG["logo"]}},
        "mainEntityOfPage": {"@type": "WebPage", "@id": bp.DOMAIN + "/" + slug + "/"},
    }


def article_breadcrumb_jsonld(slug, title):
    return {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "ホーム", "item": bp.DOMAIN + "/"},
            {"@type": "ListItem", "position": 2, "name": "コラム", "item": bp.DOMAIN + "/column/"},
            {"@type": "ListItem", "position": 3, "name": title, "item": bp.DOMAIN + "/" + slug + "/"},
        ],
    }


ARTICLES = []


def add_article(slug, title, desc, lead, sections, faq, rel):
    art = ('<article class="prose k-article">'
           + f'<p class="lead">{lead}</p>'
           + toc(sections)
           + body_from_sections(sections)
           + '</article>')
    parts = ['<div class="amt-katazuke">']
    parts.append(bp.header(""))
    parts.append('<div class="breadcrumb"><a href="/">ホーム</a>'
                 '<span>›</span><a href="/column/">コラム</a><span>›</span>' + title + '</div>')
    parts.append('<div class="page-hero hero"><div class="hero-inner">'
                 f'<div class="art-meta"><span class="art-cat">コラム</span>'
                 f'<time datetime="{TODAY_ISO}">{TODAY_JP}</time></div>'
                 f'<h1>{title}</h1></div></div>')
    parts.append('<section class="k-section">' + art + '</section>')
    parts.append(bp.faq_block(faq))
    parts.append(bp.rel_block(rel))
    parts.append(bp.cta())
    parts.append(bp.footer())
    parts.append('</div>')
    inner = "".join(parts)
    content = ('<!-- wp:html -->\n<style id="amt-katazuke-css">' + CSS + '</style>\n'
               + inner + '\n<!-- /wp:html -->')
    for j in [article_jsonld(slug, title, desc),
              article_breadcrumb_jsonld(slug, title),
              bp.faq_jsonld(faq)]:
        if j:
            content += ('\n\n<!-- wp:html -->\n<script type="application/ld+json">'
                        + json.dumps(j, ensure_ascii=False) + '</script>\n<!-- /wp:html -->')
    ARTICLES.append({"slug": slug, "title": title, "desc": desc, "content": content})


