# 関連コラム（同じカテゴリを優先して3本・<!--RELCOL--> を差し替える）
# ============================================================
def _relcol_block(slug):
    cat = ART_CAT.get(slug, "コラム")
    same = [a for a in ARTICLES if a["slug"] != slug and ART_CAT.get(a["slug"]) == cat]
    other = [a for a in ARTICLES if a["slug"] != slug and ART_CAT.get(a["slug"]) != cat]
    picks = (same + other)[:3]
    if not picks:
        return ""
    cards = "".join(
        f'<a class="relcol" href="/{a["slug"]}/">'
        f'<span class="rc-cat">{ART_CAT.get(a["slug"], "コラム")}</span>'
        f'<b>{a["title"]}</b></a>' for a in picks)
    return ('<section class="k-section" style="padding-bottom:0;"><div class="inner">'
            '<h2 class="sec-title">関連コラム</h2>'
            f'<div class="relcol-grid">{cards}</div></div></section>')


def apply_relcol():
    """全記事を組み立てたあとに、各記事の <!--RELCOL--> を関連コラムに差し替える。"""
    for a in ARTICLES:
        a["content"] = a["content"].replace("<!--RELCOL-->", _relcol_block(a["slug"]))


apply_relcol()


